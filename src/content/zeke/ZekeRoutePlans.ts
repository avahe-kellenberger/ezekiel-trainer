function scenario(data: Omit<ZekeRouteScenario, "clicks" | "openingActions">): ZekeRouteScenario {
  return { ...data, openingActions, clicks: data.actions.flatMap(({ at, action }) => action.kind === "move" ? [{ at, to: action.to }] : []) };
}

